// Writes dist/sw.js, the offline helper that lets the installed app open
// without the internet: src/sw/worker.js, preceded by the list of pages and
// files it keeps on the device. Run by `npm run build` after the pages are
// built (scripts/prerender.mjs), so it keeps exactly what was built.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Each wheel's page, by its address: index.html is "/", and
// wheel-of-business.html is "/wheel-of-business" (Cloudflare Pages serves it
// there). 404.html is not a page anyone opens on purpose.
export function pagesIn(names) {
  return names
    .filter((n) => n.endsWith('.html') && n !== '404.html')
    .map((n) => (n === 'index.html' ? '/' : `/${n.slice(0, -'.html'.length)}`))
    .sort((a, b) => (a === '/' ? -1 : b === '/' ? 1 : a.localeCompare(b)));
}

// What the pages use: everything the build made in assets/ (except the older
// .woff fonts, which only browsers without .woff2 ask for), plus the tab icon,
// the app's details and its smaller icon. Link-preview pictures, screenshots
// and the files for search engines are left on the site.
export function filesIn(assetNames) {
  return [
    ...assetNames.filter((n) => !n.endsWith('.woff')).map((n) => `/assets/${n}`).sort(),
    '/favicon.svg',
    '/manifest.webmanifest',
    '/icon-192.png',
  ];
}

export function swSource({ version, pages, files, worker }) {
  return `// GENERATED by scripts/build-sw.mjs from src/sw/worker.js. Do not edit.
const VERSION = ${JSON.stringify(version)};
const PAGES = ${JSON.stringify(pages)};
const FILES = ${JSON.stringify(files, null, 2)};

${worker}`;
}

function main() {
  const dist = path.join(root, 'dist');
  const pages = pagesIn(fs.readdirSync(dist));
  const files = filesIn(fs.readdirSync(path.join(dist, 'assets')));
  const fileOf = (url) => path.join(dist, url === '/' ? 'index.html' : pages.includes(url) ? `${url.slice(1)}.html` : url.slice(1));

  const hash = crypto.createHash('sha256');
  for (const url of [...pages, ...files]) {
    hash.update(url);
    hash.update(fs.readFileSync(fileOf(url)));
  }
  const worker = fs.readFileSync(path.join(root, 'src', 'sw', 'worker.js'), 'utf8');
  hash.update(worker);
  const version = hash.digest('hex').slice(0, 12);

  fs.writeFileSync(path.join(dist, 'sw.js'), swSource({ version, pages, files, worker }));
  console.log(`sw.js ${version}: ${pages.length} pages, ${files.length} files`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
