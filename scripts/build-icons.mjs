// Copies the drawing (SVG path) of every icon named in src/wheels/config.js
// out of @phosphor-icons/core into src/wheels/icons.generated.js.
//
// Why copy instead of importing at runtime: the page then ships only the
// ~30 icons it uses, and the same path data can be drawn both on screen
// (SVG) and into the downloadable image (canvas Path2D).
//
// Run with `npm run icons` after changing an icon name in the config.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { WHEELS, UI_ICONS } from '../src/wheels/config.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const WEIGHT = 'light';
const assets = path.join(root, 'node_modules', '@phosphor-icons', 'core', 'assets', WEIGHT);

const names = [...new Set([...WHEELS.flatMap((w) => w.slices.map((s) => s.icon)), ...UI_ICONS])].sort();

const lines = [];
for (const name of names) {
  const file = path.join(assets, `${name}-${WEIGHT}.svg`);
  let svg;
  try {
    svg = readFileSync(file, 'utf8');
  } catch {
    console.error(`Unknown icon "${name}" — no ${path.relative(root, file)}. Pick a name from https://phosphoricons.com`);
    process.exit(1);
  }
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1 || !/viewBox="0 0 256 256"/.test(svg)) {
    console.error(`Icon "${name}" is not a single path on a 256 grid; it cannot be drawn by this page.`);
    process.exit(1);
  }
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(paths[0])},`);
}

const out = `// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core (${WEIGHT} weight).
// Do not edit by hand: change the icon names in src/wheels/config.js and run
// \`npm run icons\`. Phosphor Icons are MIT licensed, (c) Phosphor Icons.

export const ICON_GRID = 256;

export const ICON_PATHS = {
${lines.join('\n')}
};
`;

writeFileSync(path.join(root, 'src', 'wheels', 'icons.generated.js'), out);
console.log(`Wrote ${names.length} icons.`);
